// In-memory cache for fetched Surahs
const cacheSurahs = new Map<number, Ayah[]>();

export async function getSurahVerses(surahNumber: number): Promise<Ayah[]> {
  // Check cache first
  if (cacheSurahs.has(surahNumber)) {
    return cacheSurahs.get(surahNumber)!;
  }

  // Check offline store
  if (OFFLINE_SURAHS[surahNumber] && OFFLINE_SURAHS[surahNumber].length >= 3) {
    // If the Surah is small and complete offline (like 1, 103, 108, 112, 113, 114)
    if ([1, 103, 108, 112, 113, 114].includes(surahNumber)) {
      cacheSurahs.set(surahNumber, OFFLINE_SURAHS[surahNumber]);
      return OFFLINE_SURAHS[surahNumber];
    }
  }

  try {
    // Fetch Arabic, Bengali, and English editions concurrently in a single clean API call
    const res = await fetch(`https://api.alquran.cloud/v1/surah/${surahNumber}/editions/quran-uthmani,bn.bengali,en.sahih`);
    if (!res.ok) {
      throw new Error(`Failed to load Surah ${surahNumber}: ${res.statusText}`);
    }
    const data = await res.json();
    if (data.code === 200 && data.data && data.data.length >= 2) {
      const arabicEd = data.data[0];
      const banglaEd = data.data[1];
      const englishEd = data.data[2] || { ayahs: [] };

      const ayahs: Ayah[] = arabicEd.ayahs.map((item: any, idx: number) => {
        const bnItem = banglaEd.ayahs[idx] || {};
        const enItem = englishEd.ayahs ? englishEd.ayahs[idx] : {};
        return {
          numberInSurah: item.numberInSurah,
          numberInQuran: item.number,
          arabicText: item.text,
          banglaText: bnItem.text || '',
          englishText: enItem.text || '',
          audioUrl: `https://cdn.islamic.network/quran/audio/128/ar.alafasy/${item.number}.mp3`,
          juz: item.juz,
          sajdah: typeof item.sajdah === 'boolean' ? item.sajdah : !!item.sajdah
        };
      });

      cacheSurahs.set(surahNumber, ayahs);
      return ayahs;
    }
  } catch (err) {
    console.warn(`AlQuran Cloud fetch error for Surah ${surahNumber}, falling back to offline or mock:`, err);
  }

  // Fallback to offline store if available
  if (OFFLINE_SURAHS[surahNumber]) {
    return OFFLINE_SURAHS[surahNumber];
  }

  return [];
}
